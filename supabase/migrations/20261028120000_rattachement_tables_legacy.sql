-- ============================================================================
-- Rattachement de 5 tables créées hors migration — comblement de la dérive
-- Date : 2026-10-28
-- ============================================================================
-- Contexte
-- --------
-- Cinq tables sont RÉELLEMENT lues par le code (`.from('…')`) mais n'ont aucun
-- `CREATE TABLE` dans supabase/migrations/ : elles ont été créées à la main, le
-- motif « script jetable » que AGENTS.md interdit (origine des 56 migrations
-- orphelines rattrapées le 19/08). Une base reconstruite depuis le dépôt les
-- perdrait — dont deux qui portent des données personnelles.
--
-- Elles figuraient jusqu'ici dans LEGACY_UNMIGRATED (scripts/check-cms-migrations.mjs)
-- pour ne pas masquer les NOUVELLES tables non migrées. Ce fichier les en sort.
--
--   cms_home_destinations  -> lib/home-data.ts, app/api/cms/home-destinations/route.ts
--   cms_seasons            -> lib/pillar-data.ts, app/api/cms/seasons/route.ts
--   site_content           -> lib/blog-supabase.ts, app/api/cms/content/route.ts
--   newsletter_subscribers -> app/api/newsletter/route.ts
--   travel_requests        -> app/api/travel-planning, app/dashboard/page.tsx
--
-- Méthode
-- -------
-- Le schéma ci-dessous n'est PAS déduit du code : il est relevé à l'identique sur
-- la base de production (information_schema.columns, pg_constraint, pg_indexes,
-- pg_policies) le 2026-10-28. Colonnes, types, valeurs par défaut, contraintes,
-- index et politiques RLS reproduisent l'existant, à la casse près.
--
--   cms_seasons.months_array est un text[] ; la colonne `emoji` est réelle et
--   consommée par app/api/cms/seasons/route.ts et components/SeasonalTable.tsx
--   (via CmsIcon) — elle est reproduite telle quelle, pas retirée.
--
-- Idempotent et SANS EFFET sur la base vivante
-- --------------------------------------------
-- IF NOT EXISTS partout, y compris sur les index. Sur la production, où les 5
-- tables existent déjà, chaque instruction est un no-op : aucune colonne n'est
-- ajoutée, aucune donnée lue, réécrite ni supprimée, aucun seed.
--
-- ⚠️ Sécurité — la base est partagée avec une autre application (voir
-- docs/CMS_FOUNDATION_PHASE_0_INVENTAIRE.md §2). Cette migration ne nomme que
-- ses propres tables et ne touche à AUCUNE politique existante. Les politiques
-- RLS reproduites sont exactement celles en place (relevé pg_policies), y compris
-- le refus de lecture anon sur travel_requests et newsletter_subscribers.
-- ============================================================================

-- ─── 1. cms_home_destinations — destinations mises en avant sur l'accueil ───
CREATE TABLE IF NOT EXISTS public.cms_home_destinations (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text        NOT NULL,
  slug        text        NOT NULL UNIQUE,
  description text,
  eyebrow     text,
  sort_order  integer     NOT NULL DEFAULT 0,
  is_active   boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ─── 2. cms_seasons — grille des saisons par destination ───────────────────
CREATE TABLE IF NOT EXISTS public.cms_seasons (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destination_slug text        NOT NULL,
  season_label     text        NOT NULL,
  months           text        NOT NULL,
  note             text,
  sort_order       integer     NOT NULL DEFAULT 0,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  emoji            text,
  months_array     text[],
  weather          text,
  crowd            text,
  price            text,
  is_active        boolean     NOT NULL DEFAULT true,
  CONSTRAINT cms_seasons_crowd_check CHECK (crowd = ANY (ARRAY['low','medium','high'])),
  CONSTRAINT cms_seasons_price_check CHECK (price = ANY (ARRAY['low','medium','high']))
);

CREATE UNIQUE INDEX IF NOT EXISTS cms_seasons_unique_idx
  ON public.cms_seasons (destination_slug, season_label);

-- ─── 3. site_content — blocs éditables du site (clé page + block_key) ──────
CREATE TABLE IF NOT EXISTS public.site_content (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page       text        NOT NULL,
  block_key  text        NOT NULL,
  value      text,
  label      text,
  type       text        DEFAULT 'text',
  updated_at timestamptz DEFAULT now(),
  CONSTRAINT site_content_page_block_key_key UNIQUE (page, block_key)
);

-- ─── 4. newsletter_subscribers — inscriptions à la lettre (donnée perso.) ──
CREATE TABLE IF NOT EXISTS public.newsletter_subscribers (
  id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  email         text        NOT NULL UNIQUE,
  source        text        NOT NULL DEFAULT 'footer',
  subscribed_at timestamptz NOT NULL DEFAULT now(),
  active        boolean     NOT NULL DEFAULT true
);

CREATE INDEX IF NOT EXISTS idx_newsletter_subscribers_email
  ON public.newsletter_subscribers (email);

-- ─── 5. travel_requests — demandes de Travel Planning (donnée perso.) ──────
CREATE TABLE IF NOT EXISTS public.travel_requests (
  id                 uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at         timestamptz NOT NULL DEFAULT now(),
  status             text        NOT NULL DEFAULT 'new',
  first_name         text,
  email              text        NOT NULL,
  phone              text,
  trip_type          text,
  vibe               text,
  destination        text,
  destination_detail text,
  duration           text,
  budget             text,
  departure_date     text,
  message            text,
  notes              text,
  updated_at         timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS travel_requests_created_at_idx
  ON public.travel_requests (created_at DESC);

-- ============================================================================
-- RLS — reproduction à l'identique des politiques en place (relevé 2026-10-28).
-- DROP POLICY IF EXISTS + CREATE = rejouable ; sur la production, les politiques
-- étant identiques, la recréation est sans effet observable.
-- ============================================================================

-- cms_home_destinations : lecture publique (contenu de vitrine), écriture service_role.
ALTER TABLE public.cms_home_destinations ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "public read cms_home_destinations" ON public.cms_home_destinations;
CREATE POLICY "public read cms_home_destinations" ON public.cms_home_destinations
  FOR SELECT TO anon USING (true);

-- cms_seasons : lecture publique, écriture service_role.
ALTER TABLE public.cms_seasons ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "public read cms_seasons" ON public.cms_seasons;
CREATE POLICY "public read cms_seasons" ON public.cms_seasons
  FOR SELECT TO anon USING (true);

-- site_content : lecture publique ; écriture authenticated + service_role.
ALTER TABLE public.site_content ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public read site_content" ON public.site_content;
CREATE POLICY "Public read site_content" ON public.site_content
  FOR SELECT TO public USING (true);
DROP POLICY IF EXISTS "Authenticated write site_content" ON public.site_content;
CREATE POLICY "Authenticated write site_content" ON public.site_content
  FOR ALL TO authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Service role write site_content" ON public.site_content;
CREATE POLICY "Service role write site_content" ON public.site_content
  FOR ALL TO service_role USING (true) WITH CHECK (true);

-- newsletter_subscribers (donnée personnelle) : insertion anonyme depuis le
-- formulaire, AUCUNE lecture anon. Seul le service_role lit.
ALTER TABLE public.newsletter_subscribers ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Anon insert newsletter" ON public.newsletter_subscribers;
CREATE POLICY "Anon insert newsletter" ON public.newsletter_subscribers
  FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "Service read newsletter" ON public.newsletter_subscribers;
CREATE POLICY "Service read newsletter" ON public.newsletter_subscribers
  FOR SELECT TO service_role USING (true);

-- travel_requests (donnée personnelle) : aucune lecture anon, service_role seul.
ALTER TABLE public.travel_requests ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Service role only" ON public.travel_requests;
CREATE POLICY "Service role only" ON public.travel_requests
  FOR SELECT TO public USING ((SELECT auth.role()) = 'service_role');

-- ============================================================================
-- Vérification (lecture seule) — les 5 tables doivent être présentes.
-- ============================================================================
SELECT t.table_name AS table_rattachee,
       (SELECT COUNT(*) FROM information_schema.columns c
         WHERE c.table_schema = 'public' AND c.table_name = t.table_name) AS nb_colonnes,
       (SELECT COUNT(*) FROM pg_policies p
         WHERE p.schemaname = 'public' AND p.tablename = t.table_name) AS nb_politiques
FROM (VALUES
  ('cms_home_destinations'), ('cms_seasons'), ('site_content'),
  ('newsletter_subscribers'), ('travel_requests')
) AS t(table_name)
WHERE EXISTS (
  SELECT 1 FROM information_schema.tables
  WHERE table_schema = 'public' AND table_name = t.table_name
)
ORDER BY t.table_name;
